"""Make a designed search dimension actually passable to the engine.

The design agent may add a dimension that the base space does not contain. That
dimension is only useful if the Trial wrapper can turn it into a vLLM flag, and
the wrapper only knows the mappings the runtime config declares. When a designed
dimension had no mapping, every Trial failed before starting a container: 36
Trials and their validation produced zero measurements.

Rather than dropping such a dimension, this derives the mapping from the flag
that the installed vLLM really accepts, which is the evidence already collected
during discovery. A dimension is kept only when the positive flag appears in
that list. A boolean dimension's negative form follows vLLM's own boolean
convention and cannot be discovered by scanning source, so it is derived and
recorded as derived rather than presented as verified.

Anything that cannot be shown to be passable is dropped and reported, because a
dimension that cannot reach the engine is worse than no dimension at all: it
silently converts every Trial into a failed one.
"""

from __future__ import annotations

from typing import Any

from evotailor.spaces.search_space import Dimension, SearchSpace

#: Dimension namespaces whose leaf maps onto a command-line flag.
FLAG_NAMESPACES = ("deployment", "runtime", "model", "vllm")


def flag_for(dimension_name: str) -> str | None:
    """Derive the vLLM flag a dimension name would become, if it has a mapping."""
    namespace, separator, leaf = dimension_name.partition(".")
    if not separator or namespace not in FLAG_NAMESPACES or not leaf:
        return None
    return "--" + leaf.replace("_", "-")


def derive_argument(
    dimension_name: str, dimension: Dimension, supported_flags: set[str]
) -> tuple[dict[str, Any] | None, str]:
    """Return ``(spec, reason)`` for turning a dimension into wrapper arguments.

    ``spec`` is None when the dimension cannot be shown to be passable, and
    ``reason`` always says why, so the decision can be recorded.
    """
    flag = flag_for(dimension_name)
    if flag is None:
        return None, (
            f"{dimension_name} does not name a flag: only "
            f"{', '.join(FLAG_NAMESPACES)} dimensions map onto the engine"
        )
    if not supported_flags:
        return None, (
            "the installed vLLM flag list is unavailable, so no new dimension can be "
            "shown to be passable"
        )
    if flag not in supported_flags:
        return None, f"the installed vLLM does not list {flag} as a supported flag"

    values = dimension.values()
    if values and all(isinstance(value, bool) for value in values):
        # The negative form is generated by the argument parser at runtime and is
        # not present in a source scan, so it is derived by convention.
        return {
            "true_flag": flag,
            "false_flag": flag.replace("--", "--no-", 1),
        }, f"{flag} is a supported boolean flag (negative form derived by convention)"
    return {"flag": flag}, f"{flag} is a supported flag"


def ensure_passable(
    space: SearchSpace,
    base: SearchSpace,
    supported_flags: set[str],
    existing_arguments: dict[str, Any] | None = None,
    probe: Any | None = None,
) -> tuple[SearchSpace, dict[str, Any], list[dict[str, str]]]:
    """Drop added dimensions the wrapper could not pass, and derive the rest.

    Returns the adjusted space, the derived argument specs, and the dropped
    dimensions with their reasons. Base dimensions are never touched: they are
    the runtime's responsibility, and the Campaign cannot remove them anyway.

    When ``probe`` is supplied, a boolean dimension's values are also tried
    against the real engine. A feature flag the platform cannot enable at all is
    not a tunable dimension, so a dimension with a value the engine refuses is
    dropped rather than left in the space to consume budget on Trials that cannot
    start.
    """
    from evotailor.selection.engine_probe import probe_dimension_values

    existing = existing_arguments or {}
    added = sorted(set(space.dimensions) - set(base.dimensions))
    derived: dict[str, Any] = {}
    dropped: list[dict[str, str]] = []
    keep: list[str] = []

    for name in added:
        if name in existing:
            keep.append(name)
            continue
        dimension = space.dimensions[name]
        spec, reason = derive_argument(name, dimension, supported_flags)
        if spec is None:
            dropped.append({"dimension": name, "reason": reason})
            continue
        evidence: list[dict[str, Any]] = []
        if probe is not None:
            _usable, evidence = probe_dimension_values(dimension, spec, probe)
            refused = [
                f"{item['value']} -> {item['reason']}" for item in evidence if not item["accepted"]
            ]
            if refused:
                dropped.append(
                    {
                        "dimension": name,
                        "reason": (
                            "a value of this dimension cannot start the engine, so it is not "
                            f"tunable on this platform: {'; '.join(refused)[:400]}"
                        ),
                    }
                )
                continue
        entry = spec | {"derived_from": reason}
        if evidence:
            entry["probe"] = evidence
        derived[name] = entry
        keep.append(name)

    if not dropped:
        return space, derived, dropped

    kept_names = set(base.dimensions) | set(keep)
    dimensions = {name: space.dimensions[name] for name in space.dimensions if name in kept_names}
    baseline = {name: value for name, value in space.safe_baseline.items() if name in kept_names}
    adjusted = SearchSpace(
        backend=space.backend,
        dimensions=dimensions,
        global_constraints=list(space.global_constraints),
        safe_baseline=baseline,
    )
    return adjusted, derived, dropped
